type avroCompatCase struct {
	name          string
	processor     string // "chunk" or "embed"
	fieldSchema   string // Avro type of field "v"; empty for a text-only payload
	value         any    // value of field "v"
	keySchema     string
	key           map[string]any
	before        bool // also set Payload.Before
	text          string
	operation     opencdc.Operation
	processorConf map[string]string
	// rawPayloadHex, when set, is fed to the chain as the payload instead of
	// an encoding of value: a hand-built malformed input.
	rawPayloadHex string
	raw           bool
	// zone is time.Local while the case encodes and runs; nil means UTC.
	zone *time.Location
}

