package embed

// Avro codec equivalence across the hamba/avro -> iskorotkov/avro move
// (ConduitIO/conduit#3012; design: ConduitIO/conduit
// docs/design-documents/20260823-avro-codec-archived-decoder-advisories.md).
//
// Neither processor touches Avro itself, but sdk.Run wraps both in the
// processor SDK's default middleware, which decodes Avro keys and payloads
// before Process and re-encodes them after. That is where the codec runs, so
// this test drives the real middleware chain around the real processors.
//
// testdata/avro_compat_fixtures.json was generated by this file on the
// previous main (processor-sdk v0.5.2 pseudo-version, commons v0.6.0, codec
// hamba/avro v2.28.0) with AVRO_COMPAT_GEN=1. It freezes, per case:
//   - the Avro bytes hamba wrote for the input key and payload;
//   - what the processor saw after the decode middleware (exact Go types);
//   - every output record (key, payload, metadata) and the schema text the
//     encode middleware registered for it, or the error string.
//
// On the new codec the test feeds the frozen hamba bytes through the same
// chain and requires identical results, and re-encodes the same Go values
// to check the new codec writes identical bytes. Invariant 6: records
// written before the move decode, and re-encode, identically after it.
// Never regenerate the fixtures with the new codec.

