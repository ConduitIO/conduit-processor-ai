func (c avroCompatCase) payloadSchema() string {
	fields := `{"name":"text","type":"string"}`
	if c.fieldSchema != "" {
		fields += `,{"name":"v","type":` + c.fieldSchema + `}`
	}
	return `{"type":"record","name":"Doc","namespace":"compat","fields":[` + fields + `]}`
}

func (c avroCompatCase) payloadValue() map[string]any {
	v := map[string]any{"text": c.text}
	if c.fieldSchema != "" {
		v["v"] = c.value
	}
	return v
}

// subject derives a unique schema subject per case so registry versions do
// not depend on the order cases run in.
func (c avroCompatCase) subject(part string) string {
	return "compat." + strings.ReplaceAll(c.name, "/", ".") + "." + part
}

// spyProcessor records what the wrapped processor receives, i.e. what the
// decode middleware produced.
type spyProcessor struct {
	sdk.Processor
	seen *[]string
}

func (s spyProcessor) Process(ctx context.Context, records []opencdc.Record) []sdk.ProcessedRecord {
	for _, r := range records {
		*s.seen = append(*s.seen, "key="+renderData(r.Key)+" before="+renderData(r.Payload.Before)+
			" after="+renderData(r.Payload.After))
	}
	return s.Processor.Process(ctx, records)
}

func newAvroCompatChain(t *testing.T, c avroCompatCase, seen *[]string) sdk.Processor {
	t.Helper()
	ctx := context.Background()

	var inner sdk.Processor
	cfg := config.Config{}
	var embedProc *Processor
	switch c.processor {
	case "chunk":
		inner = chunk.NewProcessor()
		cfg["inputField"] = ".Payload.After.text"
		cfg["outputField"] = ".Payload.After.text"
		cfg["chunkSize"] = "8"
		cfg["overlap"] = "2"
	case "embed":
		embedProc = NewProcessor()
		inner = embedProc
	default:
		t.Fatalf("unknown processor %q", c.processor)
	}
	for k, v := range c.processorConf {
		cfg[k] = v
	}

	chain := sdk.ProcessorWithMiddleware(
		spyProcessor{Processor: inner, seen: seen},
		sdk.DefaultProcessorMiddleware(inner.MiddlewareOptions()...)...,
	)
	if err := chain.Configure(ctx, cfg); err != nil {
		t.Fatalf("configure: %v", err)
	}
	if embedProc != nil {
		embedProc.provider = &fakeProvider{
			name: "fake", maxBatch: 16,
			resultFn: func(inputs []string) (BatchResult, error) {
				outcomes := make([]Outcome, len(inputs))
				for i, in := range inputs {
					outcomes[i] = Outcome{Vector: []float32{0.5, -0.25, float32(len(in))}}
				}
				return BatchResult{
					Outcomes: outcomes, Model: "fake-model", Dimension: 3,
					TokensUsed: 11, TokensScope: TokensScopeBatch,
				}, nil
			},
		}
	}
	if err := chain.Open(ctx); err != nil {
		t.Fatalf("open: %v", err)
	}
	return chain
}

func runAvroCompatCase(t *testing.T, c avroCompatCase, keyBytes, payloadBytes []byte) avroCompatFixture {
	t.Helper()
	ctx := context.Background()

	keySch, err := sdkschema.Create(ctx, schema.TypeAvro, c.subject("key"), []byte(c.keySchema))
	if err != nil {
		t.Fatalf("create key schema: %v", err)
	}
	paySch, err := sdkschema.Create(ctx, schema.TypeAvro, c.subject("payload"), []byte(c.payloadSchema()))
	if err != nil {
		t.Fatalf("create payload schema: %v", err)
	}

	rec := opencdc.Record{
		Position:  opencdc.Position("pos-1"),
		Operation: c.operation,
		Metadata:  opencdc.Metadata{"compat.case": c.name},
		Key:       opencdc.RawData(keyBytes),
		Payload:   opencdc.Change{After: opencdc.RawData(payloadBytes)},
	}
	if c.before {
		rec.Payload.Before = opencdc.RawData(payloadBytes)
	}
	if c.operation == opencdc.OperationDelete {
		rec.Payload.After = nil
	}
	schema.AttachKeySchemaToRecord(rec, keySch)
	schema.AttachPayloadSchemaToRecord(rec, paySch)

	var seen []string
	chain := newAvroCompatChain(t, c, &seen)
	out := chain.Process(ctx, []opencdc.Record{rec})

	got := avroCompatFixture{
		Name:          c.name,
		Processor:     c.processor,
		KeySchema:     c.keySchema,
		PayloadSchema: c.payloadSchema(),
		KeyHex:        hex.EncodeToString(keyBytes),
		PayloadHex:    hex.EncodeToString(payloadBytes),
		Seen:          seen,
	}
	for i, pr := range out {
		switch pr := pr.(type) {
		case sdk.SingleRecord:
			got.Outputs = append(got.Outputs, fmt.Sprintf("%d single %s", i, renderRecord(ctx, t, opencdc.Record(pr))))
		case sdk.MultiRecord:
			got.Outputs = append(got.Outputs, fmt.Sprintf("%d multi len=%d", i, len(pr)))
			for j, r := range pr {
				got.Outputs = append(got.Outputs, fmt.Sprintf("%d.%d %s", i, j, renderRecord(ctx, t, r)))
			}
		case sdk.ErrorRecord:
			got.Outputs = append(got.Outputs, fmt.Sprintf("%d error %s", i, pr.Error.Error()))
		case sdk.FilterRecord:
			got.Outputs = append(got.Outputs, fmt.Sprintf("%d filter", i))
		default:
			got.Outputs = append(got.Outputs, fmt.Sprintf("%d %T", i, pr))
		}
	}
	return got
}

func renderRecord(ctx context.Context, t *testing.T, r opencdc.Record) string {
	t.Helper()
	var sb strings.Builder
	var schemas [2]*schema.Schema
	var schemaText [2]string
	for i, part := range []struct {
		name    string
		subject func() (string, error)
		version func() (int, error)
	}{
		{"key", r.Metadata.GetKeySchemaSubject, r.Metadata.GetKeySchemaVersion},
		{"payload", r.Metadata.GetPayloadSchemaSubject, r.Metadata.GetPayloadSchemaVersion},
	} {
		subj, err1 := part.subject()
		ver, err2 := part.version()
		if err1 != nil || err2 != nil {
			continue
		}
		sch, err := sdkschema.Get(ctx, subj, ver)
		if err != nil {
			schemaText[i] = fmt.Sprintf(" %sSchema=<error %v>", part.name, err)
			continue
		}
		schemas[i] = &sch
		schemaText[i] = fmt.Sprintf(" %sSchema=%s:%s", part.name, sch.Type, string(sch.Bytes))
	}

	fmt.Fprintf(&sb, "op=%s pos=%s key=%s before=%s after=%s", r.Operation, r.Position,
		renderEncoded(r.Key, schemas[0]), renderEncoded(r.Payload.Before, schemas[1]),
		renderEncoded(r.Payload.After, schemas[1]))
	keys := make([]string, 0, len(r.Metadata))
	for k := range r.Metadata {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&sb, " md[%s]=%q", k, r.Metadata[k])
	}
	sb.WriteString(schemaText[0])
	sb.WriteString(schemaText[1])
	return sb.String()
}

// hasAvroMap reports whether an Avro schema contains a map type. The Avro
// spec leaves the order of map entries unspecified, and both codecs write
// them in Go map iteration order, so bytes of a map with two or more entries
// differ from run to run on either codec (checked on hamba: 15 generator
// runs gave 4 distinct fixture files, all differing only there).
func hasAvroMap(schemaText string) bool {
	return strings.Contains(schemaText, `"type":"map"`)
}

// renderEncoded renders raw Avro data exactly (hex), except under a schema
// with a map, where it renders the length and the decoded value with sorted
// map keys: the same entries in any order give the same string, and any
// change to an entry, a type or the size does not.
func renderEncoded(d opencdc.Data, sch *schema.Schema) string {
	raw, ok := d.(opencdc.RawData)
	if !ok || sch == nil || !hasAvroMap(string(sch.Bytes)) {
		return renderData(d)
	}
	return renderOrderFree(*sch, raw)
}

func renderOrderFree(sch schema.Schema, b []byte) string {
	var v opencdc.StructuredData
	if err := sch.Unmarshal(b, &v); err != nil {
		return fmt.Sprintf("raw(len=%d,undecodable:%v)", len(b), err)
	}
	return fmt.Sprintf("raw(len=%d,map-order-free):%s", len(b), renderValue(map[string]any(v)))
}

func renderData(d opencdc.Data) string {
	switch d := d.(type) {
	case nil:
		return "nil"
	case opencdc.RawData:
		return "raw:" + hex.EncodeToString(d)
	case opencdc.StructuredData:
		return "structured:" + renderValue(map[string]any(d))
	default:
		return fmt.Sprintf("%T", d)
	}
}

// renderValue prints v with exact Go types, deterministic map order, and no
// pointer addresses.
func renderValue(v any) string {
	switch v := v.(type) {
	case nil:
		return "nil"
	case map[string]any:
		keys := make([]string, 0, len(v))
		for k := range v {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, len(keys))
		for i, k := range keys {
			parts[i] = fmt.Sprintf("%q:%s", k, renderValue(v[k]))
		}
		return "map[string]any{" + strings.Join(parts, ",") + "}"
	case []any:
		parts := make([]string, len(v))
		for i, e := range v {
			parts[i] = renderValue(e)
		}
		return "[]any{" + strings.Join(parts, ",") + "}"
	case *big.Rat:
		if v == nil {
			return "(*big.Rat)(nil)"
		}
		return "*big.Rat(" + v.RatString() + ")"
	case time.Time:
		return "time.Time(" + v.Format(time.RFC3339Nano) + " loc=" + v.Location().String() + ")"
	case []byte:
		return fmt.Sprintf("[]byte(%x)", v)
	default:
		return fmt.Sprintf("%T(%#v)", v, v)
	}
}

// avroCodecModule reports which Avro codec module conduit-commons is built
// on, read from the type of the schema field inside its Avro serde. It is
// the codec this test actually exercises.
func avroCodecModule() string {
	f, ok := reflect.TypeOf(commonsavro.Serde{}).FieldByName("schema")
	if !ok {
		return ""
	}
	return f.Type.PkgPath()
}

// encodeAvroCompatInputs encodes the case's key and payload with the codec in
// the build. A value the codec rejects is part of the frozen behavior: the
// error text is returned instead of bytes.
func encodeAvroCompatInputs(c avroCompatCase) (keyBytes, payloadBytes []byte, encodeErr string) {
	keySch := schema.Schema{Type: schema.TypeAvro, Bytes: []byte(c.keySchema)}
	paySch := schema.Schema{Type: schema.TypeAvro, Bytes: []byte(c.payloadSchema())}
	kb, err := keySch.Marshal(c.key)
	if err != nil {
		return nil, nil, "key: " + err.Error()
	}
	pb, err := paySch.Marshal(c.payloadValue())
	if err != nil {
		return nil, nil, "payload: " + err.Error()
	}
	return kb, pb, ""
}

// generateAvroCompatFixtures writes the frozen fixtures. It runs only on the
// pre-move code (see the file comment).
func generateAvroCompatFixtures(t *testing.T, cases []avroCompatCase) {
	t.Helper()
	// Fixtures must come from the archived codec, never the new one.
	if avroCodecModule() != hambaModule {
		t.Fatalf("%s=1 refuses to run: commons is built on %q, not %s; fixtures must be generated on the pre-move code",
			avroCompatGenEnv, avroCodecModule(), hambaModule)
	}
	all := make([]avroCompatFixture, 0, len(cases))
	for _, c := range cases {
		kb, pb, encErr := encodeAvroCompatInputs(c)
		if encErr != "" {
			all = append(all, avroCompatFixture{
				Name: c.name, Processor: c.processor, KeySchema: c.keySchema,
				PayloadSchema: c.payloadSchema(), EncodeError: encErr,
			})
			continue
		}
		all = append(all, runAvroCompatCase(t, c, kb, pb))
	}
	b, err := json.MarshalIndent(all, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(avroCompatFixtures), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(avroCompatFixtures, append(b, '\n'), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %d fixtures with %s", len(all), hambaModule)
}

func TestAvroCodecCompat(t *testing.T) {
	// local-timestamp-* values are written and read relative to time.Local on
	// both codecs, so the bytes depend on the machine's zone. Pin UTC (a wasip1
	// build runs with a zero offset as well). No test in this package
	// runs in parallel, so swapping the global is safe here.
	local := time.Local                      //nolint:gosmopolitan // pinning the zone is the point
	time.Local = time.UTC                    //nolint:gosmopolitan // see above
	t.Cleanup(func() { time.Local = local }) //nolint:gosmopolitan // restore

	cases := avroCompatCases()

	if os.Getenv(avroCompatGenEnv) == "1" {
		generateAvroCompatFixtures(t, cases)
		return
	}

	if m := avroCodecModule(); m == hambaModule || m == "" {
		t.Fatalf("commons is built on %q; this module must not depend on the archived codec %s", m, hambaModule)
	}
	t.Logf("comparing %s against fixtures frozen with %s", avroCodecModule(), hambaModule)

	raw, err := os.ReadFile(avroCompatFixtures)
	if err != nil {
		t.Fatal(err)
	}
	var fixtures []avroCompatFixture
	if err := json.Unmarshal(raw, &fixtures); err != nil {
		t.Fatal(err)
	}
	byName := make(map[string]avroCompatFixture, len(fixtures))
	for _, f := range fixtures {
		byName[f.Name] = f
	}
	if len(byName) != len(cases) {
		t.Errorf("fixtures have %d cases, test defines %d: a case without a frozen fixture is not covered",
			len(byName), len(cases))
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			want, ok := byName[c.name]
			if !ok {
				t.Fatalf("no frozen fixture for %q", c.name)
			}
			if want.KeySchema != c.keySchema || want.PayloadSchema != c.payloadSchema() {
				t.Fatalf("case schemas changed since the fixtures were frozen")
			}

			// Encode: the new codec writes the bytes hamba wrote.
			kb, pb, encErr := encodeAvroCompatInputs(c)
			if encErr != want.EncodeError {
				t.Fatalf("encode error differs:\n got %q\nwant %q", encErr, want.EncodeError)
			}
			if encErr != "" {
				return // rejected identically; there are no bytes to decode
			}
			if got := hex.EncodeToString(kb); got != want.KeyHex {
				t.Errorf("key bytes differ:\n got %s\nwant %s", got, want.KeyHex)
			}
			if got := hex.EncodeToString(pb); got != want.PayloadHex {
				paySch := schema.Schema{Type: schema.TypeAvro, Bytes: []byte(c.payloadSchema())}
				wantBytes, err := hex.DecodeString(want.PayloadHex)
				if err != nil {
					t.Fatal(err)
				}
				// Only map entry order may differ, see hasAvroMap.
				if !hasAvroMap(c.payloadSchema()) ||
					renderOrderFree(paySch, pb) != renderOrderFree(paySch, wantBytes) {
					t.Errorf("payload bytes differ:\n got %s\nwant %s", got, want.PayloadHex)
				}
			}

			// Decode and re-encode: hamba-written bytes through the real
			// middleware chain give the same decoded values and outputs.
			wantKey, err := hex.DecodeString(want.KeyHex)
			if err != nil {
				t.Fatal(err)
			}
			wantPayload, err := hex.DecodeString(want.PayloadHex)
			if err != nil {
				t.Fatal(err)
			}
			got := runAvroCompatCase(t, c, wantKey, wantPayload)
			compareLines(t, "seen by processor", got.Seen, want.Seen)
			compareLines(t, "outputs", got.Outputs, want.Outputs)
		})
	}
}

func compareLines(t *testing.T, what string, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Errorf("%s: got %d lines, want %d\n got %q\nwant %q", what, len(got), len(want), got, want)
		return
	}
	for i := range got {
		if got[i] != want[i] {
			t.Errorf("%s line %d differs:\n got %s\nwant %s", what, i, got[i], want[i])
		}
	}
}
